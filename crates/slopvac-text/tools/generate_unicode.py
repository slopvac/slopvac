"""Regenerate src/unicode_data.rs from the running Python's own Unicode tables.

Run from the repository root:

    mise exec -- uv run --extra dev python crates/slopvac-text/tools/generate_unicode.py [--check]

`str.casefold` and `str.isdigit` are the reference behaviour, so the tables come from
the interpreter that defines them. They are exact for that interpreter's Unicode
version, recorded in the generated header. `--check` fails when the file differs.
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
import unicodedata
from pathlib import Path

TARGET = Path(__file__).parents[1] / "src" / "unicode_data.rs"


def escape(s: str) -> str:
    return "".join(f"\\u{{{ord(x):X}}}" for x in s)


def render() -> str:
    fold = []
    digits: list[list[int]] = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        folded = c.casefold()
        if folded != c:
            fold.append((cp, folded))
        if c.isdigit():
            if digits and digits[-1][1] == cp - 1:
                digits[-1][1] = cp
            else:
                digits.append([cp, cp])
    out = [
        "//! Generated by `tools/generate_unicode.py`; do not edit.",
        f"//! Source: Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.",
        "",
        "/// Characters whose `str.casefold()` differs from themselves, sorted by code point.",
        "pub(crate) const CASEFOLD: &[(char, &str)] = &[",
    ]
    for cp, folded in fold:
        out.append(f"    ('\\u{{{cp:X}}}', \"{escape(folded)}\"),")
    out += [
        "];",
        "",
        "/// Inclusive code point ranges where `str.isdigit()` is true.",
        "pub(crate) const DIGITS: &[(u32, u32)] = &[",
    ]
    for lo, hi in digits:
        out.append(f"    (0x{lo:X}, 0x{hi:X}),")
    out.append("];")
    return "\n".join(out) + "\n"


def formatted(text: str) -> str:
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "unicode_data.rs"
        path.write_text(text, encoding="utf-8")
        subprocess.run(["rustfmt", "--edition", "2024", str(path)], check=True)
        return path.read_text(encoding="utf-8")


def main() -> None:
    text = formatted(render())
    if "--check" in sys.argv:
        if TARGET.read_text(encoding="utf-8") != text:
            raise SystemExit("unicode_data.rs is stale; regenerate it with this script")
        return
    TARGET.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
