"""Regenerate src/unicode_data.rs from the running Python's own Unicode tables.

Run from the repository root with the interpreter that mise pins:

    mise exec -- python crates/slopvac-text/tools/generate_unicode.py [--check]

`str.casefold` and `str.isdigit` are the reference behaviour, so the tables come from
the interpreter that defines them. They are exact for that interpreter's Unicode
version, which the generated header records. The script refuses to run on any other
Unicode version (exit status 77, the "skipped" status), so every Python in the 3.14
series reproduces the same file. `--check` fails when the file differs.
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
import unicodedata
from pathlib import Path

TARGET = Path(__file__).parents[1] / "src" / "unicode_data.rs"
EXPECTED_UNICODE = "16.0.0"
WRONG_VERSION_STATUS = 77


def escape(s: str) -> str:
    return "".join(f"\\u{{{ord(x):X}}}" for x in s)


def add_range(ranges: list[list[int]], cp: int) -> None:
    if ranges and ranges[-1][1] == cp - 1:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp])


def mapping(name: str, doc: str, entries: list[tuple[int, str]]) -> list[str]:
    out = [f"/// {doc}", f"pub(crate) const {name}: &[(char, &str)] = &["]
    for cp, mapped in entries:
        out.append(f"    ('\\u{{{cp:X}}}', \"{escape(mapped)}\"),")
    return [*out, "];", ""]


def ranges_const(name: str, doc: str, ranges: list[list[int]]) -> list[str]:
    out = [f"/// {doc}", f"pub(crate) const {name}: &[(u32, u32)] = &["]
    for lo, hi in ranges:
        out.append(f"    (0x{lo:X}, 0x{hi:X}),")
    return [*out, "];", ""]


def render() -> str:
    fold: list[tuple[int, str]] = []
    lower: list[tuple[int, str]] = []
    upper: list[tuple[int, str]] = []
    digits: list[list[int]] = []
    space: list[list[int]] = []
    isupper: list[list[int]] = []
    cased: list[list[int]] = []
    ignorable: list[list[int]] = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        for table, mapped in ((fold, c.casefold()), (lower, c.lower()), (upper, c.upper())):
            if mapped != c:
                table.append((cp, mapped))
        if c.isdigit():
            add_range(digits, cp)
        if c.isspace():
            add_range(space, cp)
        if c.isupper():
            add_range(isupper, cp)
        # Python offers no public Cased / Case_Ignorable, but `str.lower` applies the
        # final-sigma rule from them, so probe it. A cased character before a capital
        # sigma makes it final. A case-ignorable character is skipped on both sides.
        is_cased = (c + "\u03a3").lower()[-1] == "\u03c2"
        if is_cased:
            add_range(cased, cp)
            # A cased character after the sigma makes it non-final unless skipped.
            is_ignorable = ("A\u03a3" + c).lower()[1] == "\u03c2"
        else:
            is_ignorable = ("A" + c + "\u03a3").lower()[-1] == "\u03c2"
        if is_ignorable:
            add_range(ignorable, cp)
    out = [
        "//! Generated by `tools/generate_unicode.py`; do not edit.",
        f"//! Source: Python `str` tables, Unicode {unicodedata.unidata_version}.",
        "",
        *mapping("CASEFOLD", "`str.casefold()` where it differs, sorted by code point.", fold),
        *mapping("LOWER", "`str.lower()` of one character where it differs; capital sigma is context-free here.", lower),
        *mapping("UPPER", "`str.upper()` of one character where it differs.", upper),
        *ranges_const("DIGITS", "Inclusive ranges where `str.isdigit()` is true.", digits),
        *ranges_const("SPACE", "Inclusive ranges where `str.isspace()` is true.", space),
        *ranges_const("UPPERCASE", "Inclusive ranges where one-character `str.isupper()` is true.", isupper),
        *ranges_const("CASED", "Inclusive ranges of cased characters (final-sigma context).", cased),
        *ranges_const(
            "CASE_IGNORABLE",
            "Inclusive ranges of case-ignorable characters (final-sigma context).",
            ignorable,
        ),
    ]
    return "\n".join(out).rstrip("\n") + "\n"


def formatted(text: str) -> str:
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "unicode_data.rs"
        path.write_text(text, encoding="utf-8")
        subprocess.run(["rustfmt", "--edition", "2024", str(path)], check=True)
        return path.read_text(encoding="utf-8")


def main() -> None:
    if unicodedata.unidata_version != EXPECTED_UNICODE:
        print(
            f"unicode_data.rs is generated from Unicode {EXPECTED_UNICODE}, but this "
            f"Python has Unicode {unicodedata.unidata_version}; use the mise-pinned Python",
            file=sys.stderr,
        )
        raise SystemExit(WRONG_VERSION_STATUS)
    text = formatted(render())
    if "--check" in sys.argv:
        if TARGET.read_text(encoding="utf-8") != text:
            raise SystemExit("unicode_data.rs is stale; regenerate it with this script")
        return
    TARGET.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
