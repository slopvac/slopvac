//! Completions, man pages and the Markdown CLI reference, all from the tree.
#![expect(
    clippy::let_underscore_must_use,
    reason = "fmt::Write for String never returns an error"
)]

use clap::Command;
use std::fmt::Write as _;
use std::io;
use std::path::Path;

/// Render the completion script for `shell`.
///
/// Rendering goes to memory first, because `clap_complete` panics on a write error.
#[must_use]
pub fn completions(shell: clap_complete::Shell) -> Vec<u8> {
    let mut cmd = crate::cli::command();
    let mut buf = Vec::new();
    clap_complete::generate(shell, &mut cmd, "slopvac", &mut buf);
    buf
}

/// Render the main man page.
pub fn man_page(cmd: &Command) -> io::Result<Vec<u8>> {
    let mut buf = Vec::new();
    clap_mangen::Man::new(cmd.clone()).render(&mut buf)?;
    Ok(buf)
}

/// Write one man page per command (`slopvac.1`, `slopvac-lint.1`, ...).
pub fn write_man_pages(dir: &Path) -> io::Result<()> {
    std::fs::create_dir_all(dir)?;
    let cmd = crate::cli::command();
    clap_mangen::generate_to(cmd, dir)
}

/// Render the CLI reference as Markdown, one section per command.
///
/// Output is deterministic so CI can compare it with the checked-in file.
#[must_use]
pub fn markdown_reference(cmd: &Command) -> String {
    let mut out = String::from("# Command-line reference\n\n");
    out.push_str("<!-- Generated by `slopvac cli-reference`. Do not edit. -->\n\n");
    section(&mut out, cmd, "slopvac", 2);
    let trimmed = out.trim_end().len();
    out.truncate(trimmed);
    out.push('\n');
    out
}

fn section(out: &mut String, cmd: &Command, path: &str, depth: usize) {
    let mut cmd = cmd.clone();
    cmd.build();
    let _ = writeln!(out, "{} `{path}`\n", "#".repeat(depth));
    if let Some(about) = cmd.get_about() {
        let _ = writeln!(out, "{about}\n");
    }
    let args: Vec<_> = cmd
        .get_arguments()
        .filter(|a| !a.is_hide_set() && a.get_id() != "help" && a.get_id() != "version")
        .collect();
    if !args.is_empty() {
        out.push_str("| Argument | Description |\n| --- | --- |\n");
        for arg in args {
            let name = match (arg.get_long(), arg.is_positional()) {
                (Some(long), _) => format!("`--{long}`"),
                (None, true) => format!("`<{}>`", arg.get_id().as_str().to_uppercase()),
                _ => format!("`{}`", arg.get_id()),
            };
            let help = arg
                .get_help()
                .map(ToString::to_string)
                .unwrap_or_default()
                .replace('|', "\\|");
            let _ = writeln!(out, "| {name} | {help} |");
        }
        out.push('\n');
    }
    for sub in cmd
        .get_subcommands()
        .filter(|s| !s.is_hide_set() && s.get_name() != "help")
    {
        section(out, sub, &format!("{path} {}", sub.get_name()), depth + 1);
    }
}
