//go:build ignore

// unicode_tables prints src/unicode_tables.rs: the Unicode tables that Go's
// unicode package gives prose v3.3.1, for the port in slopvac-pos.
//
// Run through tools/gen_unicode_tables.py, which writes the file or checks it.
package main

import (
	"fmt"
	"os"
	"runtime"
	"strings"
	"unicode"
)

type span struct{ lo, hi rune }

func collect(in func(rune) bool) []span {
	var out []span
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if !in(r) {
			continue
		}
		if n := len(out); n > 0 && out[n-1].hi+1 == r {
			out[n-1].hi = r
		} else {
			out = append(out, span{r, r})
		}
	}
	return out
}

func emit(w *strings.Builder, name, doc string, spans []span) {
	fmt.Fprintf(w, "/// %s\n#[rustfmt::skip]\n", doc)
	fmt.Fprintf(w, "pub(crate) const %s: [(u32, u32); %d] = [\n", name, len(spans))
	for i := 0; i < len(spans); i += 4 {
		w.WriteString("   ")
		for j := i; j < i+4 && j < len(spans); j++ {
			fmt.Fprintf(w, " (0x%x, 0x%x),", spans[j].lo, spans[j].hi)
		}
		w.WriteString("\n")
	}
	w.WriteString("];\n\n")
}

func main() {
	var w strings.Builder
	fmt.Fprintf(&w, "// @generated by tools/gen_unicode_tables.py (Go %s, Unicode %s). Do not edit.\n\n", runtime.Version(), unicode.Version)
	emit(&w, "UPPER", "Go `unicode.IsUpper`: category Lu.", collect(unicode.IsUpper))
	emit(&w, "LOWER", "Go `unicode.IsLower`: category Ll.", collect(unicode.IsLower))
	emit(&w, "DIGIT", "Go `unicode.IsDigit`: category Nd.", collect(unicode.IsDigit))
	emit(&w, "PUNCT_OR_SYMBOL", "Go `unicode.IsPunct` or `unicode.IsSymbol`: categories P and S.",
		collect(func(r rune) bool { return unicode.IsPunct(r) || unicode.IsSymbol(r) }))
	os.Stdout.WriteString(strings.TrimRight(w.String(), "\n") + "\n")
}
