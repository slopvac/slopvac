#!/usr/bin/env python3
"""Generate `src/tables.rs` from the Unicode Character Database.

Usage: gen_tables.py <ucd-dir> > src/tables.rs

`<ucd-dir>` holds `UnicodeData.txt` and `DerivedCoreProperties.txt` of the
version named in `UNICODE_VERSION` below. Download both from
https://www.unicode.org/Public/<version>/ucd/ and rerun the script to move to a
newer version, then bump the constant.

The table lists every code point that can forge or hide terminal output:
general categories Cc, Cf, Co, Zl and Zp; the Default_Ignorable_Code_Point
property; and the noncharacters (a stable subset of Cn). Unassigned code points
are left out, because their set changes with every Unicode version and a plain
new letter or emoji must not get escaped.
"""

import sys
from pathlib import Path

UNICODE_VERSION = "17.0.0"
CATEGORIES = {"Cc", "Cf", "Co", "Zl", "Zp"}


def unicode_data(path: Path) -> set[int]:
    points: set[int] = set()
    first = None
    for line in path.read_text(encoding="utf-8").splitlines():
        fields = line.split(";")
        code, name, category = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(", First>"):
            first = code
            continue
        low = first if name.endswith(", Last>") and first is not None else code
        first = None
        if category in CATEGORIES:
            points.update(range(low, code + 1))
    return points


def default_ignorable(path: Path) -> set[int]:
    points: set[int] = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        span, prop, *_ = (part.strip() for part in body.split(";"))
        if prop != "Default_Ignorable_Code_Point":
            continue
        low, _, high = span.partition("..")
        points.update(range(int(low, 16), int(high or low, 16) + 1))
    return points


def noncharacters() -> set[int]:
    points = set(range(0xFDD0, 0xFDF0))
    for plane in range(17):
        points.update((plane << 16 | 0xFFFE, plane << 16 | 0xFFFF))
    return points


def ranges(points: set[int]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for p in sorted(points):
        if out and out[-1][1] + 1 == p:
            out[-1] = (out[-1][0], p)
        else:
            out.append((p, p))
    return out


def hex_literal(n: int) -> str:
    """Hex with `_` every four digits, as clippy's unreadable_literal wants."""
    digits = f"{n:x}"
    if len(digits) <= 4:
        return f"0x{digits}"
    digits = digits.zfill(-(-len(digits) // 4) * 4)
    return "0x" + "_".join(digits[i : i + 4] for i in range(0, len(digits), 4))


def main() -> None:
    ucd = Path(sys.argv[1])
    points = (
        unicode_data(ucd / "UnicodeData.txt")
        | default_ignorable(ucd / "DerivedCoreProperties.txt")
        | noncharacters()
    )
    rows = ranges(points)
    print("// @generated by tools/gen_tables.py. Do not edit by hand.")
    print(f"// Source: Unicode Character Database {UNICODE_VERSION}.")
    print()
    print("/// Version of the Unicode Character Database behind the table.")
    print(f'pub const UNICODE_VERSION: &str = "{UNICODE_VERSION}";')
    print()
    print("/// Sorted, non-overlapping, inclusive ranges of code points to escape.")
    print("pub(crate) const UNSAFE: &[(u32, u32)] = &[")
    for low, high in rows:
        print(f"    ({hex_literal(low)}, {hex_literal(high)}),")
    print("];")


if __name__ == "__main__":
    main()
