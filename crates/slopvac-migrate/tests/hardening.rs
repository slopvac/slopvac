//! Hardening cases from the config epic's review: unmappable members are reported,
//! inline-array overrides migrate, rule-table comments survive, and this
//! repository's own 2.x config round-trips.

use slopvac_migrate::{Error, Options, RenameTable, migrate_config};
use toml_edit::{DocumentMut, Item};

const REPO_2X: &str = include_str!("fixtures/repo-2x.toml");

fn migrate(text: &str) -> Result<String, Error> {
    migrate_config(
        text,
        "slopvac.toml",
        &RenameTable::bundled(),
        Options::default(),
    )
    .map(|r| r.text)
}

fn dropped(text: &str) -> Vec<(String, usize)> {
    match migrate(text) {
        Err(Error::Dropped(d)) => d.into_iter().map(|d| (d.key, d.line)).collect(),
        other => panic!("expected Dropped, got {other:?}"),
    }
}

fn doc(text: &str) -> DocumentMut {
    text.parse().expect("valid TOML")
}

fn strings(item: &Item) -> Vec<String> {
    item.as_array()
        .expect("array")
        .iter()
        .map(|v| v.as_str().expect("string").to_owned())
        .collect()
}

#[test]
fn this_repository_config_migrates_with_its_data_and_comments() {
    let out = migrate(REPO_2X).unwrap();
    let (before, after) = (doc(REPO_2X), doc(&out));
    assert_eq!(after["schema_version"].as_integer(), Some(3));
    assert_eq!(after["profile"].as_str(), Some("normal"));
    assert_eq!(strings(&after["exclude"]), strings(&before["exclude"]));
    assert_eq!(after["thresholds"]["max_errors"].as_integer(), Some(0));
    let categories = after["categories"].as_table().unwrap();
    let names: Vec<_> = categories.iter().map(|(k, _)| k.to_owned()).collect();
    assert_eq!(
        names,
        [
            "core:ste-descriptive",
            "core:ste-nouns",
            "core:ste-practices",
            "core:ste-procedural",
            "core:ste-punctuation",
            "core:ste-sentences",
            "core:ste-verbs",
            "core:ste-words",
        ]
    );
    assert!(
        categories
            .iter()
            .all(|(_, v)| v.as_str() == Some("suggestion"))
    );
    let overrides = after["overrides"].as_array_of_tables().unwrap();
    assert_eq!(overrides.len(), 1);
    assert_eq!(
        strings(&overrides.get(0).unwrap()["files"]),
        ["**/README.md"]
    );
    assert_eq!(
        overrides.get(0).unwrap()["thresholds"]["min_score"].as_integer(),
        Some(0)
    );
    for comment in [
        "# The prose gate for this repository",
        "# --- Simplified Technical English",
        "# The score combines weighted category scores",
        "# This README override disables the minimum-score gate.",
        "# Generated by `slopvac reference`",
        "# The Contributor Covenant 2.1",
    ] {
        assert!(out.contains(comment), "lost `{comment}`");
    }
}

#[test]
fn this_repository_config_does_not_migrate_twice() {
    let once = migrate(REPO_2X).unwrap();
    assert!(matches!(migrate(&once), Err(Error::AlreadyMigrated { .. })));
}

#[test]
fn every_unmappable_locale_and_vocabulary_member_is_reported_at_once() {
    let d = dropped(
        "[locale]\ndefault = \"en-GB\"\nbogus = 1\nother = 2\n[vocabulary]\npath = \"w.toml\"\nextra = 3\n",
    );
    assert_eq!(
        d,
        [
            ("locale.bogus".to_owned(), 3),
            ("locale.other".to_owned(), 4),
            ("vocabulary.extra".to_owned(), 7),
        ]
    );
}

#[test]
fn unmappable_members_in_an_override_are_reported_with_their_path() {
    let d = dropped(
        "[[overrides]]\nfiles = [\"a\"]\n[overrides.locale]\ndefault = \"en-GB\"\nbogus = 1\n",
    );
    assert_eq!(d, [("overrides[0].locale.bogus".to_owned(), 5)]);
}

#[test]
fn extension_keys_are_noted_not_silently_deleted() {
    let rw = migrate_config(
        "[locale]\ndefault = \"en-GB\"\nx-team = \"docs\"\n",
        "slopvac.toml",
        &RenameTable::bundled(),
        Options::default(),
    )
    .unwrap();
    assert_eq!(
        rw.notes
            .iter()
            .filter(|n| n.contains("locale.x-team"))
            .count(),
        1
    );
}

fn extension_notes(text: &str) -> (String, Vec<String>) {
    let rw = migrate_config(
        text,
        "slopvac.toml",
        &RenameTable::bundled(),
        Options::default(),
    )
    .unwrap();
    let notes = rw
        .notes
        .into_iter()
        .filter(|n| n.contains("extension key"))
        .collect();
    (rw.text, notes)
}

#[test]
fn vocabulary_extension_key_is_noted_and_the_path_survives() {
    let (text, notes) = extension_notes("[vocabulary]\npath = \"w.toml\"\nx-owner = \"docs\"\n");
    assert_eq!(notes, ["dropped extension key vocabulary.x-owner"]);
    assert_eq!(strings(&doc(&text)["terms"]["blocklists"]), ["w.toml"]);
    assert!(!text.contains("x-owner"), "{text}");
}

#[test]
fn override_vocabulary_extension_key_is_noted_with_the_override_path() {
    let (text, notes) = extension_notes(
        "[[overrides]]\nfiles = [\"a\"]\n[overrides.vocabulary]\npath = \"w.toml\"\nx-owner = \"docs\"\n",
    );
    assert_eq!(
        notes,
        ["dropped extension key overrides[0].vocabulary.x-owner"]
    );
    let after = doc(&text);
    let ov = after["overrides"].as_array_of_tables().unwrap();
    assert_eq!(
        strings(&ov.get(0).unwrap()["terms"]["blocklists"]),
        ["w.toml"]
    );
}

#[test]
fn inline_override_vocabulary_extension_key_is_noted_with_the_override_path() {
    let (text, notes) = extension_notes(
        "overrides = [{ files = [\"a\"], vocabulary = { path = \"w.toml\", x-owner = \"docs\" } }]\n",
    );
    assert_eq!(
        notes,
        ["dropped extension key overrides[0].vocabulary.x-owner"]
    );
    let after = doc(&text);
    let first = after["overrides"].as_array().unwrap().get(0).unwrap();
    let terms = Item::Value(first.as_inline_table().unwrap()["terms"].clone());
    assert_eq!(strings(&terms["blocklists"]), ["w.toml"]);
}

#[test]
fn locale_extension_key_note_is_qualified_in_an_override() {
    let (_, notes) = extension_notes(
        "[[overrides]]\nfiles = [\"a\"]\n[overrides.locale]\ndefault = \"en-GB\"\nx-team = \"docs\"\n",
    );
    assert_eq!(notes, ["dropped extension key overrides[0].locale.x-team"]);
}

#[test]
fn inline_array_overrides_migrate_like_array_tables() {
    let out = migrate(
        "overrides = [{ files = [\"a\"], locale = { default = \"en-GB\", allow = [\"x\"] } }, { files = [\"b\"], vocabulary = { path = \"w.toml\" }, rules = { \"orwell.not-un\" = \"off\" } }]\n",
    )
    .unwrap();
    let after = doc(&out);
    let ov = after["overrides"].as_array().unwrap();
    let first = ov.get(0).unwrap().as_inline_table().unwrap();
    assert_eq!(first["locale"].as_str(), Some("en-GB"));
    assert_eq!(
        strings(&Item::Value(first["terms"].clone())["allow"]),
        ["x"]
    );
    let second = ov.get(1).unwrap().as_inline_table().unwrap();
    assert_eq!(
        strings(&Item::Value(second["terms"].clone())["blocklists"]),
        ["w.toml"]
    );
    assert_eq!(
        Item::Value(second["rules"].clone())["core:orwell.not-un"].as_str(),
        Some("off")
    );
    assert!(!second.contains_key("vocabulary"));
}

#[test]
fn inline_array_overrides_report_unmappable_settings() {
    let d = dropped(
        "overrides = [{ files = [\"a\"], vale = { binary = \"v\" } }, { files = [\"b\"], guidance = { write = \"off\" } }]\n",
    );
    assert_eq!(
        d,
        [
            ("overrides[0].vale.binary".to_owned(), 1),
            ("overrides[1].guidance".to_owned(), 1),
        ]
    );
}

#[test]
fn rule_table_comments_move_to_the_bare_level() {
    let out = migrate(
        "[rules]\n# why this is off\n[rules.\"orwell.not-un\"] # header note\n# about the level\nseverity = \"off\" # trailing\n",
    )
    .unwrap();
    assert!(
        out.contains(
            "# why this is off\n# header note\n# about the level\n\"core:orwell.not-un\" = \"off\" # trailing\n"
        ),
        "{out}"
    );
}

#[test]
fn category_table_comments_move_to_the_bare_level() {
    let out =
        migrate("# keep STE quiet\n[categories.ste-words]\nseverity = \"suggestion\"\n").unwrap();
    assert!(
        out.contains("# keep STE quiet\n\"core:ste-words\" = \"suggestion\"\n"),
        "{out}"
    );
}
