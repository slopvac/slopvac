//! The 2.x to 3.0 migration step, through the public interface.

use serde_json::json;
use slopvac_config::migrate::{IdentityRenames, Renames, migrate};
use slopvac_config::tree::parse_toml;
use slopvac_config::{Code, ConfigError, validate_config};

fn json_of(text: &str) -> serde_json::Value {
    parse_toml(text).unwrap().to_json()
}

fn diagnostics(err: ConfigError) -> (String, Vec<slopvac_config::Diagnostic>) {
    match err {
        ConfigError::Rejected(r) => (r.text, r.diagnostics),
        other @ ConfigError::Io { .. } => panic!("expected a rejection, got {other}"),
    }
}

const TABLES_2X: &str = r#"profile = "strict"

[locale]
default = "en-GB"
allow = ["colour"]

[vocabulary]
path = "vocab.toml"

[vale]
enabled = false
binary = "vale"

[rules."a.b"]
severity = "off"

[categories.x]
severity = "warning"

[[overrides]]
files = ["docs/**"]

[overrides.locale]
default = "en-US"
allow = ["z"]

[overrides.rules.r]
severity = "error"
"#;

struct Qualify;

impl Renames for Qualify {
    fn rule(&self, old: &str) -> Option<String> {
        match old {
            "a.b" => Some("core:a-b".into()),
            "r" => Some("core:r".into()),
            _ => None,
        }
    }

    fn category(&self, old: &str) -> Option<String> {
        Some(format!("cat-{old}"))
    }
}

#[test]
fn every_table_of_a_2x_config_moves_to_its_3_0_place() {
    let out = migrate("slopvac.toml", TABLES_2X, &Qualify).unwrap();
    assert_eq!(
        json_of(&out.text),
        json!({
            "schema_version": 3,
            "profile": "strict",
            "locale": "en-GB",
            "terms": {"allow": ["colour"], "blocklists": ["vocab.toml"]},
            "rules": {"core:a-b": "off"},
            "categories": {"cat-x": {"severity": "warning"}},
            "overrides": [{
                "files": ["docs/**"],
                "locale": "en-US",
                "terms": {"allow": ["z"]},
                "rules": {"core:r": "error"}
            }]
        })
    );
    assert!(out.text.starts_with("schema_version = 3\n"));
    assert_eq!(
        validate_config(&parse_toml(&out.text).unwrap(), &out.text),
        []
    );
}

#[test]
fn the_change_list_names_each_step_in_order() {
    let out = migrate("slopvac.toml", TABLES_2X, &Qualify).unwrap();
    assert_eq!(out.changes[0], "added `schema_version = 3`");
    for expected in [
        "moved `locale.default` to `locale`",
        "moved `locale.allow` to `terms.allow`",
        "moved `vocabulary.path` to `terms.blocklists`",
        "removed `vale` (Vale is gone in 3.0)",
        "renamed `rules.a.b` to `rules.core:a-b`",
        "wrote `rules.core:a-b` as a bare level",
        "moved `overrides[0].locale.default` to `overrides[0].locale`",
        "renamed `overrides[0].rules.r` to `overrides[0].rules.core:r`",
    ] {
        assert!(
            out.changes.iter().any(|c| c == expected),
            "missing {expected:?} in {:#?}",
            out.changes
        );
    }
}

#[test]
fn this_repository_config_migrates_with_comments_kept() {
    let text = include_str!("fixtures/repo-2x.toml");
    let out = migrate("slopvac.toml", text, &IdentityRenames).unwrap();
    assert!(out.text.contains("# Generated by `slopvac reference`"));
    assert!(out.text.contains("# --- Simplified Technical English"));
    let before = json_of(text);
    let mut after = json_of(&out.text);
    assert_eq!(after["schema_version"], 3);
    after.as_object_mut().unwrap().remove("schema_version");
    assert_eq!(after, before);
    assert_eq!(
        validate_config(&parse_toml(&out.text).unwrap(), &out.text),
        []
    );
}

#[test]
fn migration_is_deterministic_and_idempotent() {
    let first = migrate("slopvac.toml", TABLES_2X, &Qualify).unwrap();
    let again = migrate("slopvac.toml", TABLES_2X, &Qualify).unwrap();
    assert_eq!(first, again);
    let twice = migrate("slopvac.toml", &first.text, &Qualify).unwrap();
    assert_eq!(twice.text, first.text);
    assert_eq!(twice.changes, Vec::<String>::new());
}

#[test]
fn a_version_2_file_migrates_like_a_file_with_no_version() {
    let marked = format!("schema_version = 2\n{TABLES_2X}");
    let a = migrate("slopvac.toml", &marked, &Qualify).unwrap();
    let b = migrate("slopvac.toml", TABLES_2X, &Qualify).unwrap();
    assert_eq!(json_of(&a.text), json_of(&b.text));
}

#[test]
fn a_newer_version_is_refused_with_an_upgrade_hint() {
    let err = migrate("slopvac.toml", "schema_version = 9\n", &Qualify).unwrap_err();
    let (_, d) = diagnostics(err);
    assert_eq!(d[0].code, Code::UnsupportedVersion);
    assert_eq!(d[0].help.as_deref(), Some("upgrade slopvac"));
}

#[test]
fn every_setting_without_a_home_is_reported_in_one_run_and_nothing_is_written() {
    let text = "[vale]\nenabled = true\nbinary = \"vale\"\n\n[rules.nope]\nseverity = \"off\"\n\n[rules.\"a.b\"]\nseverity = \"off\"\nreason = \"x\"\n\n[[overrides]]\nfiles = [\"a\"]\n\n[overrides.vale]\nconfig = \".vale.ini\"\n";
    let (src, d) = diagnostics(migrate("slopvac.toml", text, &Qualify).unwrap_err());
    assert!(d.iter().all(|x| x.code == Code::LegacyDropped));
    let found: Vec<(String, (usize, usize))> = d
        .iter()
        .map(|x| (src[x.span.clone()].to_owned(), x.location(&src)))
        .collect();
    assert_eq!(
        found,
        [
            ("enabled".to_owned(), (2, 1)),
            ("binary".to_owned(), (3, 1)),
            ("nope".to_owned(), (5, 8)),
            ("reason".to_owned(), (10, 1)),
            ("config".to_owned(), (16, 1)),
        ]
    );
}

#[test]
fn vale_settings_are_dropped_without_complaint_when_vale_is_disabled() {
    let text =
        "[vale]\nenabled = false\nbinary = \"vale\"\nconfig = \".vale.ini\"\nstyles = [\"x\"]\n";
    let out = migrate("slopvac.toml", text, &IdentityRenames).unwrap();
    assert_eq!(json_of(&out.text), json!({"schema_version": 3}));
}

#[test]
fn an_unparsable_file_is_a_parse_error() {
    let (_, d) = diagnostics(migrate("slopvac.toml", "a = = 1\n", &Qualify).unwrap_err());
    assert_eq!(d[0].code, Code::Parse);
}
